// Builds the Solar icon subset used by the app (CLAUDE.md §5 Icons).
// - Every name is checked against the official Solar set (@iconify-json/solar); a missing name fails the build.
// - Bold Duotone icons are rewritten so the secondary (50% opacity) layer uses var(--icon-secondary),
//   letting us paint them in --purple + --purple-light instead of one colour at two opacities.
// Run: node scripts/build-icons.mjs   (add new intents to ICONS below, then re-run)
