// Generates data/showtimes.json: 7 days of demo shows with realistic, clustered bookings (CLAUDE.md §9.5 Data).
// Deterministic (seeded), so re-running gives the same file for the same start date.
// Run: node scripts/generate-showtimes.mjs [YYYY-MM-DD]   (default start: 2026-11-23)
import { readFileSync, writeFileSync } from "node:fs";
import { buildSeats, priceBandFor } from "../lib/halls.ts";

const START = process.argv[2] ?? "2026-11-23";
const DAYS = 7;
const read = (f) => JSON.parse(readFileSync(new URL(`../data/${f}`, import.meta.url), "utf8"));
const { halls } = read("halls.json");
const { movies } = read("movies.json");
const { branches } = read("branches.json");

// mulberry32
let seed = 20261123;
const rand = () => {
  seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (arr) => arr[Math.floor(rand() * arr.length)];

const nowShowing = movies.filter((m) => m.status === "now-showing");
// Not every film plays everywhere (drives the "Not at this branch" state, §9.9)
const lineup = (branch) => {
  if (branch === "bashundhara-city") return nowShowing;
  const n = 3 + Math.floor(rand() * 2);
  return [...nowShowing].sort(() => rand() - 0.5).slice(0, n);
};

const SLOTS = {
  premium: ["10:30", "13:15", "16:00", "18:45", "21:30"],
  vip: ["11:00", "14:00", "17:15", "20:15"],
  atmos: ["12:00", "15:15", "18:30", "21:45"],
};

function addDays(iso, n) {
  const d = new Date(`${iso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

/** Books ~occupancy of the hall in groups of 2–4 adjacent seats (single seats occasionally). */
function bookSeats(hall, occupancy) {
  const seats = buildSeats(hall);
  const byRow = new Map();
  for (const s of seats) {
    if (!byRow.has(s.row)) byRow.set(s.row, []);
    byRow.get(s.row).push(s);
  }
  for (const row of byRow.values()) row.sort((a, b) => a.col - b.col);
  const target = Math.round(seats.length * occupancy);
  const booked = new Set();
  // middle rows and centre seats fill first, like real audiences
  const rows = [...byRow.keys()];
  const rowWeight = (i) => 1 - Math.abs(i / (rows.length - 1) - 0.55) * 0.9;
  let guard = 0;
  while (booked.size < target && guard++ < 10000) {
    const ri = Math.floor(rand() * rows.length);
    if (rand() > rowWeight(ri)) continue;
    const row = byRow.get(rows[ri]);
    const centreBias = Math.min(row.length - 1, Math.max(0, Math.round(row.length / 2 + (rand() + rand() - 1) * row.length * 0.6)));
    const size = rand() < 0.12 ? 1 : 2 + Math.floor(rand() * 3);
    for (let k = 0; k < size && booked.size < target; k++) {
      const s = row[centreBias + k];
      if (!s) break;
      // a gap between groups breaks adjacency in the grid → stop the group there
      if (k > 0 && s.col - row[centreBias + k - 1].col > 1) break;
      booked.add(s.id);
    }
  }
  return [...booked].sort();
}

const showtimes = [];
for (const branch of branches) {
  const branchHalls = halls.filter((h) => h.branch === branch.slug);
  const films = lineup(branch.slug);
  for (let d = 0; d < DAYS; d++) {
    const date = addDays(START, d);
    branchHalls.forEach((hall, hi) => {
      SLOTS[hall.type].forEach((time, si) => {
        const movie = films[(si + hi * 2 + d) % films.length];
        const band = priceBandFor(date, time);
        const base = { matinee: 0.25, evening: 0.55, weekend: 0.65 }[band];
        let occ = Math.min(0.96, Math.max(0.08, base + (rand() - 0.5) * 0.4));
        if (rand() < 0.03) occ = 1; // the occasional sold-out show (§9.9)
        const format = hall.type === "atmos" ? "Atmos" : movie.format;
        showtimes.push({
          id: `${hall.id}-${date.replaceAll("-", "")}-${time.replace(":", "")}`,
          branch: branch.slug,
          hall: hall.id,
          movie: movie.slug,
          date,
          time,
          format,
          priceBand: band,
          bookedSeats: bookSeats(hall, occ),
        });
      });
    });
  }
}

const out = {
  _note: `Demo showtimes generated by scripts/generate-showtimes.mjs for ${START} + ${DAYS - 1} days. Bookings are fake. Public holidays are not marked yet.`,
  showtimes,
};
writeFileSync(new URL("../data/showtimes.json", import.meta.url), JSON.stringify(out) + "\n");
console.log(`Wrote ${showtimes.length} showtimes`);
